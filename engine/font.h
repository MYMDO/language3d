// Pixels per character cell (fixed 8x8, no kerning, no scaling).
constexpr int FONT_W = 8;
constexpr int FONT_H = 8;

// Draw one glyph; fully clipped to the framebuffer. Returns pixels set.
inline size_t draw_glyph(uint8_t* pixels, uint16_t width, uint16_t height,
                         uint32_t stride, int x, int y, unsigned code,
                         uint8_t color) {
    if (!pixels) return 0;
    const uint8_t* g = font_glyph(code);
    size_t set = 0;
    for (int row = 0; row < 8; ++row) {
        const int py = y + row;
        if (py < 0 || py >= int(height)) continue;
        const uint8_t bits = g[row];
        if (!bits) continue;
        for (int col = 0; col < 8; ++col) {
            if (!(bits & uint8_t(0x80u >> col))) continue;
            const int px = x + col;
            if (px < 0 || px >= int(width)) continue;
            pixels[size_t(py) * stride + size_t(px)] = color;
            ++set;
        }
    }
    return set;
}

// Draw a NUL-terminated string left-to-right. Returns pixels set.
inline size_t draw_text(uint8_t* pixels, uint16_t width, uint16_t height,
                        uint32_t stride, int x, int y, const char* text,
                        uint8_t color) {
    if (!pixels || !text) return 0;
    size_t set = 0;
    int cx = x;
    for (const char* p = text; *p; ++p, cx += FONT_W) {
        set += draw_glyph(pixels, width, height, stride, cx, y,
                          (unsigned char)*p, color);
    }
    return set;
}

constexpr size_t text_width(size_t chars) { return chars * FONT_W; }

